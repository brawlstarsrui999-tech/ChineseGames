def build_levels(raw: list[dict]) -> "OrderedDict[int, list[dict]]":
    """Словарь уровень → список слов (без дублей, с чистым переводом)."""
    merged: "OrderedDict[str, dict]" = OrderedDict()

    for item in sorted(raw, key=lambda w: (int(w.get("level") or 6), w.get("id") or 0)):
        hanzi = (item.get("hanzi") or "").strip()
        if not hanzi:
            continue
        level = int(item.get("level") or 6)
        pinyin = (item.get("pinyin") or "").strip()
        translations = item.get("translations") or {}
        rus = list(translations.get("rus") or [])
        eng = list(translations.get("eng") or [])

        existing = merged.get(hanzi)
        if existing is not None:
            # полифония: объединяем чтения, уровень берём минимальный
            if pinyin and pinyin not in existing["pinyins"]:
                existing["pinyins"].append(pinyin)
            existing["level"] = min(existing["level"], level)
            for value in rus:
                if value not in existing["rus"]:
                    existing["rus"].append(value)
            for value in eng:
                if value not in existing["eng"]:
                    existing["eng"].append(value)
            continue

        merged[hanzi] = {
            "hanzi": hanzi,
            "pinyins": [pinyin] if pinyin else [],
            "level": level,
            "rus": rus,
            "eng": eng,
        }

    levels: "OrderedDict[int, list[dict]]" = OrderedDict((lvl, []) for lvl in EXPECTED_LEVELS)
    for word in merged.values():
        if not EXTRA_RUS.get(word["hanzi"]) and not word["rus"]:
            # без русского перевода слово в курс не берём (таких после EXTRA_RUS нет)
            continue
        all_rus = list(word["rus"])
        extra = EXTRA_RUS.get(word["hanzi"])
        if extra:
            all_rus = [extra] + all_rus
        translation = pick_translation(all_rus, word["eng"])
        if not translation:
            continue
        levels[word["level"]].append(
            {
                "h": word["hanzi"],
                "p": " / ".join(py.replace(" ", "") for py in word["pinyins"][:2]),
                "t": translation,
            }
        )
    return levels


def chunk_words(words: list[dict], size: int = GROUP_SIZE) -> list[list[dict]]:
    """Режем раздел на группы примерно по [size] слов, без «огрызков» по 1–2 слова."""
    if not words:
        return []
    groups_count = max(1, round(len(words) / size))
    base, extra = divmod(len(words), groups_count)
    groups = []
    index = 0
    for i in range(groups_count):
        take = base + (1 if i < extra else 0)
        groups.append(words[index:index + take])
        index += take
    return [g for g in groups if g]


def build_topic_index() -> dict[str, tuple[str, str]]:
    return {topic_id: (title, emoji) for topic_id, title, emoji, _g, _p in TOPIC_RULES}


def main(source: str | None) -> int:
    from pypinyin import lazy_pinyin, Style  # noqa: PLC0415
    try:
        import jieba  # noqa: PLC0415
    except ImportError:
        print("нужен jieba: pip install jieba")
        return 1

    raw = load_source(source)
    levels = build_levels(raw)
    titles = build_topic_index()
    titles[MISC_TOPIC[0]] = (MISC_TOPIC[1], MISC_TOPIC[2])

    os.makedirs(OUT_DIR, exist_ok=True)

    cumulative: set[str] = set()
    report: list[str] = []
    total_words = 0

    for level, words in levels.items():
        cumulative.update(w["h"] for w in words)

        by_topic: "OrderedDict[str, list[dict]]" = OrderedDict()
        for word in words:
            topic_id = classify(word["h"], word["t"], " ".join([word["t"]]))
            by_topic.setdefault(topic_id, []).append(word)

        # разделы с малым числом слов сливаем в «Разное»
        final_topics: "OrderedDict[str, list[dict]]" = OrderedDict()
        for topic_id, topic_words in by_topic.items():
            if len(topic_words) < MIN_TOPIC_WORDS and topic_id != MISC_TOPIC[0]:
                final_topics.setdefault(MISC_TOPIC[0], []).extend(topic_words)
            else:
                final_topics.setdefault(topic_id, []).extend(topic_words)

        payload = {"level": level, "words": len(words), "topics": []}
        for topic_id, topic_words in final_topics.items():
            title, emoji = titles[topic_id]
            groups = chunk_words(topic_words)
            payload["topics"].append(
                {
                    "id": f"l{level}_{topic_id}",
                    "title": title,
                    "emoji": emoji,
                    "groups": [[[w["h"], w["p"], w["t"]] for w in g] for g in groups],
                }
            )
            report.append(
                f"  HSK {level} · {title:22s} {len(topic_words):4d} слов · {len(groups):3d} групп"
            )

        total_words += len(words)
        expected = EXPECTED_LEVELS[level]
        flag = "" if abs(len(words) - expected) <= 3 else f"  (ожидалось {expected})"
        report.insert(0, f"HSK {level}: {len(words)} слов, разделов {len(payload['topics'])}{flag}")
        report.insert(0, "")

        out_path = os.path.join(OUT_DIR, f"level{level}.json")
        with open(out_path, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, ensure_ascii=False, separators=(",", ":"))
        report.insert(0, f"-> {out_path} ({os.path.getsize(out_path)} байт)")
        report.insert(0, "")

    # ------------------------------ Предложения ------------------------------ #
    topics_by_level: "OrderedDict[int, list[dict]]" = OrderedDict()
    problems: list[str] = []
    extras: list[str] = []
    sentence_total = 0
    for topic in SENTENCE_TOPICS:
        level = topic["level"]
        cumulative_upto = set()
        for lvl, words in levels.items():
            cumulative_upto.update(w["h"] for w in words)
            if lvl == level:
                break
        higher_vocab = set()
        for lvl, words in levels.items():
            if lvl > level:
                higher_vocab.update(w["h"] for w in words)

        entries = []
        for hanzi, russian in topic["sentences"]:
            tokens = [t for t in jieba.lcut(hanzi) if t.strip()]
            han_tokens = [t for t in tokens if re.search(r"[\u4e00-\u9fff]", t)]
            for token in han_tokens:
                if token_ok(token, cumulative_upto):
                    continue
                if token_is_higher_level(token, cumulative_upto, higher_vocab):
                    problems.append(f"HSK {level}: «{token}» — слово более высокого уровня (в «{hanzi}»)")
                else:
                    extras.append(f"HSK {level}: «{token}» нет в списках HSK (в «{hanzi}»)")
            pinyin_tokens = []
            for token in tokens:
                if re.search(r"[\u4e00-\u9fff]", token):
                    pinyin_tokens.append("".join(lazy_pinyin(token, style=Style.TONE)))
                else:
                    pinyin_tokens.append(token)
            pinyin = " ".join(pinyin_tokens)
            pinyin = re.sub(r"\s+([，。！？；：、])", r"\1", pinyin).strip()
            ru_words = [w.strip(" ,.!?;:«»\"'") for w in russian.split()]
            ru_words = [w for w in ru_words if w]
            entries.append([hanzi, pinyin, russian, han_tokens, ru_words])
        topics_by_level.setdefault(level, []).append(
            {
                "id": topic["id"],
                "title": topic["title"],
                "emoji": topic["emoji"],
                "sentences": entries,
            }
        )
        sentence_total += len(entries)

    levels_out = [
        {"level": level, "topics": topics} for level, topics in sorted(topics_by_level.items())
    ]

    sent_path = os.path.join(OUT_DIR, "sentences.json")
    with open(sent_path, "w", encoding="utf-8") as fh:
        json.dump({"levels": levels_out}, fh, ensure_ascii=False, separators=(",", ":"))

    print("=== Курс «Поэтапное изучение» ===")
    print(f"Слов всего: {total_words}, разделов по всем уровням, предложений: {sentence_total}")
    for line in report:
        print(line)
    print(f"-> {sent_path} ({os.path.getsize(sent_path)} байт)")
    if problems:
        print("\nОШИБКИ: в предложениях есть слова более высоких уровней HSK:")
        for line in dict.fromkeys(problems):
            print(" ", line)
    else:
        print("\nВ предложениях нет слов из более высоких уровней HSK ✔")
    if extras:
        print(f"\nПримечание: {len(set(extras))} слов вне официальных списков HSK "
              f"(имена, реалии, обычные слова вроде 今年/人们 — для уровня подходят):")
        for line in list(dict.fromkeys(extras))[:12]:
            print(" ", line)
        print("  …")
    return 1 if problems else 0


