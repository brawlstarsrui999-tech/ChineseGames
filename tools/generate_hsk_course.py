# Порядок важен: первое совпавшее правило выигрывает, поэтому конкретные темы
# идут раньше общих («есть» → «Еда», а не «Действия»).
TOPIC_ORDER = [
    "polite", "pronouns", "numbers", "time", "people", "geography", "food",
    "body", "study", "science", "society", "work", "city", "home", "nature",
    "clothes", "hobby", "communication", "feelings", "qualities", "grammar",
    "change", "actions",
]

TOPIC_RULES.sort(key=lambda rule: TOPIC_ORDER.index(rule[0]))

# Запасные правила: если слово не подошло ни под одну тему, смотрим на часть речи.
VERB_RE = re.compile(r"^\s*(не\s+)?[а-яё]+(?:ть|ться|чь|сти|зти|чься)\b|^\s*to\s+[a-z]", re.I)
ADJ_RE = re.compile(r"^\s*[а-яё]+(?:ый|ий|ой|ая|яя|ое|ее|ие|ые|им|ем)\b|^\s*\w+(?:ive|ous|ful|able|ible|al)\b", re.I)


# Имена собственные и устойчивые термины, которых нет в списках HSK, но которые
# встречаются в учебниках на соответствующем этапе.
SENTENCE_ALLOW = {
    "安娜", "上海", "西安", "欧洲", "春节", "汉字", "人工智能", "通货膨胀",
    "书法", "全球化", "媒体", "居民", "作家", "作家", "联合国", "孔子",
}


# Служебные суффиксы: «打得», «睡得» — это знакомый глагол + частица.
PARTICLE_SUFFIX = "得着了过的地"


def decomposable(token: str, vocab: set[str]) -> bool:
    """Слово целиком собирается из знакомых слов (看电视 → 看 + 电视)."""
    rest = token
    while rest:
        for size in range(min(len(rest), 6), 0, -1):
            if rest[:size] in vocab:
                rest = rest[size:]
                break
        else:
            return False
    return True


def token_ok(token: str, vocab: set[str]) -> bool:
    """Слово «из уровня»: есть в списке, либо собирается из знакомых слов."""
    if token in vocab or token in SENTENCE_ALLOW:
        return True
    if all(ch in vocab for ch in token):
        return True
    if len(token) >= 2 and token[-1] in PARTICLE_SUFFIX and token[:-1] in vocab:
        return True
    return decomposable(token, vocab)


def token_is_higher_level(token: str, vocab: set[str], higher: set[str]) -> bool:
    """Слово есть в HSK, но на более позднем уровне — это настоящая ошибка."""
    if token in higher:
        return True
    if len(token) >= 2 and decomposable(token, higher):
        return not decomposable(token, vocab)
    return False


def classify(hanzi: str, gloss: str, eng: str) -> str:
    """Определяем раздел слова по иероглифу и переводу."""
    text = f"{gloss} {eng}".lower()
    for topic_id, _title, _emoji, glyphs, _patterns in TOPIC_RULES:
        if hanzi in glyphs:
            return topic_id
    for topic_id, _title, _emoji, _glyphs, patterns in TOPIC_RULES:
        for pattern in patterns:
            if re.search(pattern, text):
                return topic_id
    # Запасной вариант: глаголы — в «Действия», прилагательные — в «Качества».
    for gloss_part in (gloss, eng):
        if VERB_RE.match(gloss_part):
            return "actions"
    for gloss_part in (gloss, eng):
        if ADJ_RE.match(gloss_part):
            return "qualities"
    return MISC_TOPIC[0]


