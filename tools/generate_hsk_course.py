def load_source(path: str | None) -> list[dict]:
    """Читаем hsk.json: из файла, по URL или через git clone."""
    if path and os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)

    try:
        with urllib.request.urlopen(SOURCE_URL, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except Exception as err:  # noqa: BLE001
        print(f"не удалось скачать по URL ({err}), пробую git clone…")

    tmp = tempfile.mkdtemp(prefix="hsk-")
    try:
        subprocess.run(
            ["git", "clone", "--depth", "1", SOURCE_REPO, os.path.join(tmp, "repo")],
            check=True, capture_output=True,
        )
        with open(os.path.join(tmp, "repo", "hsk.json"), encoding="utf-8") as fh:
            return json.load(fh)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# --------------------------------------------------------------------------- #
#                          Чистка переводов                                   #
