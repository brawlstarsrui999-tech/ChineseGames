BRACKETS = re.compile(r"[（(].*?[)）]")
CL_NOTE = re.compile(r"^(сч\.?\s*слово|счетное слово|сл\.?\s*слово|частица|союз|предлог|послелог|наречие)\b", re.I)


def clean_gloss(raw: str) -> str:
    """Убираем служебные пометки, оставляем короткие понятные значения."""
    text = BRACKETS.sub(" ", raw)
    text = text.replace("|", " ").strip(" ,;:")
    text = re.sub(r"\s+", " ", text)
    return text


ABBREV_FIXES = {
    "вопросит.": "вопросительная",
    "утвердит.": "утвердительная",
    "восклицат.": "восклицательная",
    "употребляется для выражения дроби и процентного соотношения":
        "для дробей и процентов (三分之一, 百分之…)",
}


def fix_abbrev(text: str) -> str:
    """Разворачиваем словарные сокращения, чтобы подпись была понятной."""
    for short, full in ABBREV_FIXES.items():
        text = text.replace(short, full)
    return text.strip()


def pick_translation(rus: list[str], eng: list[str]) -> str:
    """Собираем короткую русскую подпись слова (не длиннее ~38 символов)."""
    # Английский gloss берём только как запасной вариант: приложение русское.
    source = list(rus) if rus else list(eng)
    glosses: list[str] = []
    for raw in source + [""]:
        gloss = clean_gloss(raw)
        if not gloss:
            continue
        if CL_NOTE.match(gloss):
            continue
        # служебные описания вроде «модальный глагол…» не показываем
        if len(gloss) > 60:
            continue
        low = gloss.lower()
        if low.isdigit() and any(not g.lower().isdigit() for g in glosses):
            continue
        if not any(g.lower() == low for g in glosses):
            glosses.append(gloss)
        if len(glosses) >= 3:
            break

    if not glosses:
        # служебные слова описаны только в скобках («(вопросит. частица)») —
        # берём содержимое скобок, иначе 吗/分之 просто пропали бы из курса
        for raw in source:
            inner = BRACKETS.findall(raw)
            # findall без групп возвращает совпадение вместе со скобками — чистим их
            body = inner[0].strip("()（） ") if inner else raw
            gloss = clean_gloss(body)
            if gloss:
                glosses.append(fix_abbrev(gloss))
                break

    joined = ""
    for gloss in glosses[:3]:
        candidate = gloss if not joined else f"{joined}; {gloss}"
        if len(candidate) > 38 and joined:
            break
        joined = candidate
    return joined.strip()


